int fault_classify(const float x[FM_N_FEATURES]) {
    float z[5]; int i,j; int best=0; float bestv;
    float xs[5];
    for (i=0;i<5;i++) xs[i]=(x[i]-LR_MEAN[i])/LR_SCALE[i];
    for (j=0;j<5;j++){
        float s=LR_INT[j];
        for(i=0;i<5;i++) s+=LR_COEF[j][i]*xs[i];
        z[j]=s;
    }
    bestv=z[0];
    for(j=1;j<5;j++) if(z[j]>bestv){bestv=z[j];best=j;}
    return best;
}
